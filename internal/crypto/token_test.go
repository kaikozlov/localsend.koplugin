// TestMixedKeyTypeCrossVerification tests interop between Ed25519 and RSA-PSS clients.
// In a real scenario, sender might be Ed25519 (Go CLI) and receiver RSA-PSS (web client).
func TestMixedKeyTypeCrossVerification(t *testing.T) {
	// Go CLI uses Ed25519
	ed25519Key, _ := GenerateKeyPair()
	// Web client uses RSA
	rsaKey, _ := rsa.GenerateKey(rand.Reader, 2048)
	rsaVerifyingKey := &RsaPssVerifyingKey{publicKey: &rsaKey.PublicKey}

	// Exchange nonces
	senderNonce, _ := GenerateNonce()
	receiverNonce, _ := GenerateNonce()
	combinedNonce := append(senderNonce, receiverNonce...)

	// Ed25519 (sender/Go CLI) generates token
	ed25519Token, _ := ed25519Key.GenerateTokenWithNonce(combinedNonce)

	// RSA (receiver/web) verifies Ed25519 token
	err := VerifyTokenNonce(ed25519Key.ToVerifyingKey(), ed25519Token, combinedNonce)
	if err != nil {
		t.Errorf("Web client should verify Ed25519 token: %v", err)
	}

	// RSA (receiver/web) generates response token
	pubKeyDER, _ := x509.MarshalPKIXPublicKey(&rsaKey.PublicKey)
	digest := createDigestFromDER(pubKeyDER, combinedNonce)
	hashed := sha256.Sum256(digest)
	opts := &rsa.PSSOptions{SaltLength: rsa.PSSSaltLengthEqualsHash, Hash: gocrypto.SHA256}
	signature, _ := rsa.SignPSS(rand.Reader, rsaKey, gocrypto.SHA256, hashed[:], opts)

	hashBase64 := base64.RawURLEncoding.EncodeToString(digest)
	saltBase64 := base64.RawURLEncoding.EncodeToString(combinedNonce)
	signatureBase64 := base64.RawURLEncoding.EncodeToString(signature)
	rsaToken := "sha256." + hashBase64 + "." + saltBase64 + ".rsa-pss." + signatureBase64

	// Ed25519 (sender/Go CLI) verifies RSA-PSS token
	err = VerifyTokenNonce(rsaVerifyingKey, rsaToken, combinedNonce)
	if err != nil {
		t.Errorf("Go CLI should verify RSA-PSS token: %v", err)
	}

	t.Log("Mixed Ed25519/RSA-PSS cross-verification succeeded")
}

