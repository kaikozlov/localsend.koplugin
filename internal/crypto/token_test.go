// TestTokenCrossVerificationFlow simulates a complete sender/receiver handshake.
// This is the most critical test for protocol interoperability.
func TestTokenCrossVerificationFlow(t *testing.T) {
	// Both parties generate their own key pairs
	senderKey, err := GenerateKeyPair()
	if err != nil {
		t.Fatalf("Failed to generate sender key: %v", err)
	}
	receiverKey, err := GenerateKeyPair()
	if err != nil {
		t.Fatalf("Failed to generate receiver key: %v", err)
	}

	// Phase 1: Nonce Exchange
	// Sender generates and sends nonce first
	senderNonce, err := GenerateNonce()
	if err != nil {
		t.Fatalf("Failed to generate sender nonce: %v", err)
	}

	// Receiver generates their nonce
	receiverNonce, err := GenerateNonce()
	if err != nil {
		t.Fatalf("Failed to generate receiver nonce: %v", err)
	}

	// Both calculate combined nonce: sender_nonce || receiver_nonce
	senderCombinedNonce := append(senderNonce, receiverNonce...)
	receiverCombinedNonce := append(senderNonce, receiverNonce...)

	// Phase 2: Token Exchange
	// Sender generates token using combined nonce
	senderToken, err := senderKey.GenerateTokenWithNonce(senderCombinedNonce)
	if err != nil {
		t.Fatalf("Failed to generate sender token: %v", err)
	}

	// Receiver verifies sender's token
	err = VerifyTokenNonce(senderKey.ToVerifyingKey(), senderToken, receiverCombinedNonce)
	if err != nil {
		t.Fatalf("Receiver failed to verify sender token: %v", err)
	}

	// Receiver generates their response token
	receiverToken, err := receiverKey.GenerateTokenWithNonce(receiverCombinedNonce)
	if err != nil {
		t.Fatalf("Failed to generate receiver token: %v", err)
	}

	// Sender verifies receiver's token
	err = VerifyTokenNonce(receiverKey.ToVerifyingKey(), receiverToken, senderCombinedNonce)
	if err != nil {
		t.Fatalf("Sender failed to verify receiver token: %v", err)
	}

	t.Log("Full token exchange flow verified successfully")
}

