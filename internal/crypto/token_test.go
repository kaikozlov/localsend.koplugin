// TestRsaPssTokenGenAndVerify tests complete RSA-PSS token generation and verification.
// This simulates how web LocalSend clients (which use RSA) would authenticate.
func TestRsaPssTokenGenAndVerify(t *testing.T) {
	// Generate RSA key pair for testing
	rsaKey, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil {
		t.Fatalf("Failed to generate RSA key: %v", err)
	}

	// Create verifying key from the public portion
	verifyingKey := &RsaPssVerifyingKey{publicKey: &rsaKey.PublicKey}

	// Generate a nonce
	nonce, err := GenerateNonce()
	if err != nil {
		t.Fatalf("Failed to generate nonce: %v", err)
	}

	// Manually create an RSA-PSS token (simulating what a web client does)
	pubKeyDER, err := x509.MarshalPKIXPublicKey(&rsaKey.PublicKey)
	if err != nil {
		t.Fatalf("Failed to marshal public key: %v", err)
	}

	digest := createDigestFromDER(pubKeyDER, nonce)

	// Sign using RSA-PSS (same approach as web clients)
	hashed := sha256.Sum256(digest)
	opts := &rsa.PSSOptions{
		SaltLength: rsa.PSSSaltLengthEqualsHash,
		Hash:       gocrypto.SHA256,
	}
	signature, err := rsa.SignPSS(rand.Reader, rsaKey, gocrypto.SHA256, hashed[:], opts)
	if err != nil {
		t.Fatalf("Failed to sign with RSA-PSS: %v", err)
	}

	// Create token in protocol format
	hashBase64 := base64.RawURLEncoding.EncodeToString(digest)
	saltBase64 := base64.RawURLEncoding.EncodeToString(nonce)
	signatureBase64 := base64.RawURLEncoding.EncodeToString(signature)
	token := "sha256." + hashBase64 + "." + saltBase64 + ".rsa-pss." + signatureBase64

	// Verify the token
	err = VerifyTokenNonce(verifyingKey, token, nonce)
	if err != nil {
		t.Errorf("RSA-PSS token verification failed: %v", err)
	}
}

