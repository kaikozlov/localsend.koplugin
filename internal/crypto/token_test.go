// TestTimestampTokenExpiryBoundary tests the exact 1-hour expiry boundary.
// Implementation uses `> 3600` so exactly 3600 is the last valid second.
func TestTimestampTokenExpiryBoundary(t *testing.T) {
	key, _ := GenerateKeyPair()

	// Generate token that's 3601 seconds old (should be expired, > 3600)
	expiredSalt := make([]byte, 8)
	timestamp := uint64(time.Now().Unix() - 3601)
	for i := 0; i < 8; i++ {
		expiredSalt[i] = byte(timestamp >> (8 * i))
	}
	expiredToken, _ := key.GenerateToken(expiredSalt)

	err := VerifyTokenTimestamp(key.ToVerifyingKey(), expiredToken)
	if err == nil {
		t.Error("Token at 3601 seconds should be expired")
	}

	// Generate token that's exactly 3600 seconds old (should still be valid, = 3600)
	boundaryValidSalt := make([]byte, 8)
	timestamp = uint64(time.Now().Unix() - 3600)
	for i := 0; i < 8; i++ {
		boundaryValidSalt[i] = byte(timestamp >> (8 * i))
	}
	boundaryValidToken, _ := key.GenerateToken(boundaryValidSalt)

	err = VerifyTokenTimestamp(key.ToVerifyingKey(), boundaryValidToken)
	if err != nil {
		t.Errorf("Token at exactly 3600 seconds should still be valid: %v", err)
	}

	// Generate token that's 3599 seconds old (should definitely be valid)
	validSalt := make([]byte, 8)
	timestamp = uint64(time.Now().Unix() - 3599)
	for i := 0; i < 8; i++ {
		validSalt[i] = byte(timestamp >> (8 * i))
	}
	validToken, _ := key.GenerateToken(validSalt)

	err = VerifyTokenTimestamp(key.ToVerifyingKey(), validToken)
	if err != nil {
		t.Errorf("Token at 3599 seconds should be valid: %v", err)
	}
}

